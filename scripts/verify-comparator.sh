#!/bin/bash
# verify-comparator.sh — the statements of the headline theorems are pinned (docs/trusted-surface.md,
# "Statements pinned by the Lean comparator"). Fails if
#   1. lean/Comparator/Challenge.lean or a config changed without the pinned hash
#      (scripts/generated/comparator-challenge.sha256) changing with it: a statement change
#      needs the owner's review, and has to say so by updating the hash in the same change;
#   2. lean/Comparator/Solution.lean is not the one generated from the challenge;
#   3. a source under lean/Evm names something `_native` (only native_decide / bv_decide
#      generate those auxiliary axioms, which comparator-native.json permits by name);
#   4. `lake comparator` (Lean's built-in judge; the version is lean/lean-toolchain's) rejects
#      either set: a statement differs from the challenge's, a proof uses sorry or an axiom
#      outside the config's permitted_axioms, or the kernel rejects the proof closure.
# Step 4 needs bwrap (Linux user namespaces); elsewhere it is skipped, loudly. CI runs it.
set -euo pipefail
cd "$(dirname "$0")/../lean"

sha() { if command -v sha256sum >/dev/null; then sha256sum "$@"; else shasum -a 256 "$@"; fi; }
pinned=../scripts/generated/comparator-challenge.sha256
files=(Comparator/Challenge.lean Comparator/comparator.json Comparator/comparator-native.json)

# the solution (checked in step 2): each Pinned.<x> proved by <x>, at <x>'s own type, with the challenge's imports
gen_solution() {
  awk '
    /^import / {imps[++ni]=$0}
    /^namespace / {ns=$2}
    /^theorem Pinned\./ {sub(/^theorem Pinned\./,""); names[++k]=ns"."$1}
    END {
      print "/- GENERATED by scripts/verify-comparator.sh from Comparator/Challenge.lean: do not edit."
      print "   Each pinned theorem is proved by the real one, at the real one'"'"'s own type (`type_of%`),"
      print "   so the comparator compares the real statement with the reviewed one. Same imports as the"
      print "   challenge (and never the challenge itself: the pinned names would clash). -/"
      for (i=1;i<=ni;i++) print imps[i]
      print ""
      for (i=1;i<=k;i++) {
        full=names[i]; m=full; sub(/\.[^.]*$/,"",m); t=full; sub(/^.*\./,"",t)
        print "theorem " m ".Pinned." t " : type_of% @" full " := @" full
      }
    }' Comparator/Challenge.lean
}
[ "${1:-}" = --print-solution ] && { gen_solution; exit 0; }

# 1. the reviewed statements
if ! diff -q "$pinned" <(sha "${files[@]}") >/dev/null; then
  echo "FAIL: the pinned statements changed (lean/Comparator/: the challenge or a config)."
  echo "  A change here needs the owner's review. If approved, record it:"
  echo "    (cd lean && shasum -a 256 ${files[*]} > $pinned)"
  diff "$pinned" <(sha "${files[@]}") || true
  exit 1
fi
echo "pinned statements hash OK"

# 2. the solution
if ! diff -q Comparator/Solution.lean <(gen_solution) >/dev/null; then
  echo "FAIL: lean/Comparator/Solution.lean is stale; regenerate it:"
  echo "  scripts/verify-comparator.sh --print-solution > lean/Comparator/Solution.lean"
  diff Comparator/Solution.lean <(gen_solution) | head -20 || true
  exit 1
fi
echo "solution in sync OK"

# 3. no hand-made auxiliary-axiom names
if grep -rn '_native' Evm --include='*.lean'; then
  echo "FAIL: a source names something '_native' (reserved for native_decide's auxiliary axioms)"
  exit 1
fi

# 4. the judge
if ! command -v bwrap >/dev/null || [ "$(uname -s)" != Linux ]; then
  echo "SKIPPED: lake comparator needs bwrap on Linux (CI runs it); steps 1-3 passed"
  exit 0
fi
for cfg in comparator comparator-native; do
  rc=0
  lake comparator --config "Comparator/$cfg.json" >"/tmp/_$cfg.log" 2>&1 || rc=$?
  if [ "$rc" -ne 0 ] || ! grep -q '^Your solution is okay!' "/tmp/_$cfg.log"; then
    echo "FAIL: lake comparator --config Comparator/$cfg.json (exit $rc):"
    grep -v '^Exporting ' "/tmp/_$cfg.log" | tail -30; exit 1
  fi
  echo "$cfg: $(python3 -c "import json;print(len(json.load(open('Comparator/$cfg.json'))['theorem_names']))") statements accepted OK"
done
